/**
 * Адрес сайта. Пока проект живёт локально, но ссылки в сообщениях мастеру,
 * robots и sitemap должны собираться из одного места, чтобы при появлении
 * домена его хватило поменять в одной переменной.
 */
export function siteUrl(): string {
  return (process.env.SITE_URL ?? "http://localhost:3000").replace(/\/$/, "");
}
